/// Strings for one language. `T.of(context)('key')`, with `{name}`
/// placeholders filled from [args]. Falls back to English, then to the key.
class T {
  const T(this.lang);
  final String lang;

  static T of(BuildContext context) => context.dependOnInheritedWidgetOfExactType<LangScope>()?.t ?? const T('en');

  String call(String key, [Map<String, Object?> args = const {}]) {
    var s = _dict[lang]?[key] ?? _dict['en']![key] ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  /// Short month names, for dates such as "3 Oct, 14:05".
  List<String> get months => _months[lang] ?? _months['en']!;

  /// An API timestamp as a short local date and time in this language.
  String dateTime(String? ts) => shortDateTime(ts, months, lang);

  /// A local calendar day: "3 Oct" (Chinese "10月3日").
  String date(DateTime d) => lang == 'zh' ? '${months[d.month - 1]}${d.day}日' : '${d.day} ${months[d.month - 1]}';

  /// Short weekday name; [weekday] as in [DateTime.weekday] (1 = Monday).
  String weekday(int weekday) => (_weekdays[lang] ?? _weekdays['en']!)[(weekday - 1) % 7];

  /// "now", "5m", "3h", "2d" — how long ago, in this language.
  String ago(DateTime then) {
    final (n, unit) = shortAgo(then);
    return call('time.$unit', {'n': n});
  }
}

/// Puts the current language below MaterialApp.
class LangScope extends InheritedWidget {
  LangScope({super.key, required String lang, required super.child}) : t = T(lang);
  final T t;

  @override
  bool updateShouldNotify(LangScope old) => old.t.lang != t.lang;
}

